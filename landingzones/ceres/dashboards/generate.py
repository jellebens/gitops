def override(name, **props):
    """override("pH low", color="red", dash=True, axis="right", hide_legend=True)"""
    out = []
    if "color" in props:
        out.append({"id": "color", "value": {"mode": "fixed", "fixedColor": props["color"]}})
    if props.get("dash"):
        out.append({"id": "custom.lineStyle", "value": {"fill": "dash", "dash": [10, 10]}})
    if "axis" in props:
        out.append({"id": "custom.axisPlacement", "value": props["axis"]})
    if "unit" in props:
        out.append({"id": "unit", "value": props["unit"]})
    if props.get("no_fill"):
        out.append({"id": "custom.fillOpacity", "value": 0})
    if props.get("stairs"):
        out.append({"id": "custom.lineInterpolation", "value": "stepAfter"})
    if "max" in props:
        out.append({"id": "max", "value": props["max"]})
    if "min" in props:
        out.append({"id": "min", "value": props["min"]})
    if "width" in props:
        out.append({"id": "custom.width", "value": props["width"]})
    if props.get("hide_legend"):
        out.append({"id": "custom.hideFrom", "value": {"legend": True, "tooltip": False, "viz": False}})
    matcher = {"id": "byRegexp", "options": name[1:]} if name.startswith("~") else {"id": "byName", "options": name}
    return {"matcher": matcher, "properties": out}


