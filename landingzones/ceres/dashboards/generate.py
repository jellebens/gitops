PLAIN_SELECTOR = re.compile(r"[A-Za-z_:][A-Za-z0-9_:]*(\{(?:[^{}]|\$\{[^}]*\})*\})?")  # {unit="${unit}", …} nests a brace


def W(expr):
    """Fold the pod churn away: every rollout gives a gauge a new {pod, instance} series and a
    range query then returns one series per pod that lived in the window (found on the first
    render of the unit board — three ONLINEs in one stat)."""
    return f"max without (pod, instance) ({expr})"


def prom(expr, legend="", ref="A", instant=False, table=False):
    if not instant and PLAIN_SELECTOR.fullmatch(expr):
        expr = W(expr)
    t = {"datasource": PROM, "refId": ref, "expr": expr, "legendFormat": legend or "__auto",
         "range": not instant, "instant": instant, "editorMode": "code"}
    if table:
        t["format"] = "table"
    return t


def flux(query, ref="A"):
    return {"datasource": INFLUX, "refId": ref, "query": query}


def sql(raw, ref="A"):
    return {"datasource": PG, "refId": ref, "rawSql": raw, "format": "table", "rawQuery": True, "editorMode": "code"}


def tele(metric, zone, name, fn="mean", unit="${unit}", ref="A"):
    """One numeric telemetry series from the archive, windowed to the panel."""
    return flux(ref=ref, query=
        'from(bucket: "ceres") |> range(start: v.timeRangeStart, stop: v.timeRangeStop)'
        f' |> filter(fn: (r) => r._measurement == "unit_tele" and r.unit == "{unit}" and r.zone == "{zone}"'
        f' and r.metric == "{metric}" and r._field == "value")'
        f' |> aggregateWindow(every: v.windowPeriod, fn: {fn}, createEmpty: false)'
        f' |> keep(columns: ["_time", "_value"]) |> rename(columns: {{_value: "{name}"}})')


def meta_string(metric, name, actuator=None, unit="${unit}", start="v.timeRangeStart", stop="v.timeRangeStop", ref="A"):
    """A retained string (state/reason/status) from unit_meta as a time series of strings."""
    act = f' and r.actuator == "{actuator}"' if actuator else ""
    return flux(ref=ref, query=
        f'from(bucket: "ceres") |> range(start: {start}, stop: {stop})'
        f' |> filter(fn: (r) => r._measurement == "unit_meta" and r.unit == "{unit}" and r.metric == "{metric}"{act}'
        f' and r._field == "value") |> keep(columns: ["_time", "_value"]) |> rename(columns: {{_value: "{name}"}})')


