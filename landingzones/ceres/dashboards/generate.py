BOARDS = {"ceres-unit.json": unit_board, "ceres-fleet.json": fleet_board, "ceres-operations.json": ops_board}


def render(build):
    return json.dumps(build(), indent=1, ensure_ascii=False) + "\n"


def main(argv):
    check = "--check" in argv
    stale = []
    for name, build in BOARDS.items():
        path = HERE / name
        text = render(build)
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(HERE.parent.parent.parent)}")
    if stale:
        print("stale (run generate.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
